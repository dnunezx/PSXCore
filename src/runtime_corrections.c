    error = np_patch_add(set, 0x002036b0, gte_swc_filter_expected, gte_swc_filter_corrected, sizeof(gte_swc_filter_expected));
    if (error) return error;
    static const unsigned char gte_swc_loop_expected[4] = {
        0xe2, 0xff, 0xa0, 0x14
    };
