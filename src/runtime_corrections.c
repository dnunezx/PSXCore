    error = np_patch_add(set, 0x00203720, gte_swc_color_expected, gte_swc_color_corrected, sizeof(gte_swc_color_expected));
    if (error) return error;
    static const unsigned char gte_swc_limit_expected[4] = {
        0x00, 0x00, 0x00, 0x00
    };
