"""Validate reviewed compatibility manifests and generate portable C catalogs."""
import argparse
import json
from pathlib import Path
import re

RUNTIME='59df3389c4df88a572daa720b05507c52c34eddfa0031a6fbeec55e0c2d0fcb1'
ENV={'ps2':1,'pcsx2':2}
BUILTINS={'license':(1,{'ps2','pcsx2'}),'readback':(2,{'pcsx2'})}

def require(value,message):
    if not value:raise ValueError(message)

def string(value,limit=160):
    require(isinstance(value,str) and 0<len(value)<=limit and all(32<=ord(c)<127 for c in value),'Bounded printable ASCII string required')
    return json.dumps(value)

def common(item):
    require(item.get('schema')==1,'Unknown manifest schema')
    require(re.fullmatch(r'[a-z][a-z0-9-]{0,63}',item.get('id','')),'Invalid manifest id')
    require(item.get('runtime_sha256')==RUNTIME,'Unsupported runtime fingerprint')
    envs=item.get('environments',[])
    require(isinstance(envs,list) and envs and len(envs)==len(set(envs)) and set(envs)<=ENV.keys(),'Invalid environments')
    validation=item.get('validation',{})
    require(validation.get('status')=='tested-experimental' and set(envs)<=set(validation.get('tested_environments',[])),'Untested environment cannot be enabled')
    string(validation.get('evidence'));string(validation.get('notes'),512)
    return set(envs)

def catalog(root):
    # Former texture-wrap bit 4 is retired: wrapping is now mandatory core code.
    fixes=dict(BUILTINS);patches=[];profiles=[];symbols=set();bits={1,2,4};ids=set()
    for path in sorted((root/'patches').glob('*.json')):
        item=json.loads(path.read_text());envs=common(item);name=item['id']
        bit=item.get('bit',0);symbol=item.get('symbol','')
        require(name not in fixes,'Duplicate fix id')
        require(type(bit) is int and 4<=bit<=0x80000000 and bit&(bit-1)==0 and bit not in bits,'Unique single fix bit required')
        require(re.fullmatch(r'NP_FIX_[A-Z][A-Z0-9_]{0,47}',symbol) and symbol not in symbols and symbol not in ('NP_FIX_ALL','NP_FIX_CATALOG_MASK','NP_FIX_LICENSE','NP_FIX_READBACK','NP_FIX_TEXTURE_WRAP'),'Invalid or duplicate fix symbol')
        writes=item.get('writes',[]);require(isinstance(writes,list) and 1<=len(writes)<=64,'Bounded patch writes required')
        intervals=[]
        for write in writes:
            address=int(write['address'],0)
            require(all(isinstance(write[k],str) and re.fullmatch(r'(?:[0-9a-f]{2}){1,32}',write[k]) for k in ('expected','replacement')),'Bounded lowercase hex bytes required')
            expected=bytes.fromhex(write['expected']);replacement=bytes.fromhex(write['replacement'])
            require(len(expected)==len(replacement) and expected!=replacement,'Equal-length changed bytes required')
            require(0<=address and address+len(expected)<=0xffffffff,'Patch address overflow')
            require(not (address<0x21d6a8 and 0x21d6a4<address+len(expected)),'Optional patch overlaps mandatory core correction')
            require(not any(address<b and a<address+len(expected) for a,b in intervals),'Overlapping patch writes')
            intervals.append((address,address+len(expected)))
        fixes[name]=(bit,envs);bits.add(bit);symbols.add(symbol);patches.append(item)
    identities=set()
    for path in sorted((root/'profiles').glob('*.json')):
        item=json.loads(path.read_text());envs=common(item)
        require(item['id'] not in ids,'Duplicate profile id');ids.add(item['id'])
        require(re.fullmatch(r'[A-Z]{4}_[0-9]{3}\.[0-9]{2}',item.get('serial','')),'Canonical serial required')
        require(re.fullmatch(r'[0-9a-f]{64}',item.get('disc_sha256','')) and int(item['disc_sha256'],16)!=0,'Full nonzero disc SHA-256 required')
        string(item.get('game'));string(item.get('revision'))
        names=item.get('fixes',[])
        require(isinstance(names,list) and names and len(names)==len(set(names)) and all(n in fixes for n in names),'Unknown or duplicate profile fixes')
        require(all(envs<=fixes[n][1] for n in names),'Fix unavailable in profile environment')
        for env in envs:
            key=(item['serial'],item['disc_sha256'],env)
            require(key not in identities,'Ambiguous profile identity');identities.add(key)
        selected=[p for p in patches if p['id'] in names];intervals=[]
        for patch in selected:
            for write in patch['writes']:
                a=int(write['address'],0);b=a+len(bytes.fromhex(write['expected']))
                require(not any(a<d and c<b for c,d in intervals),'Conflicting profile patches');intervals.append((a,b))
        require(len(intervals)<=64,'Profile patch limit exceeded')
        profiles.append(item)
    return patches,profiles,fixes

def render(root):
    patches,profiles,fixes=catalog(root)
    public=['/* Generated by tools/compatibility/generate_profiles.py; edit manifests. */',
        '#ifndef PSXCORE_PROFILE_CATALOG_H','#define PSXCORE_PROFILE_CATALOG_H']
    for p in patches:public.append('#define %s %uu'%(p['symbol'],p['bit']))
    public+=['#define NP_FIX_CATALOG_MASK %uu'%sum(p['bit'] for p in patches),'#endif','']
    bytearray_c=lambda data:'{'+','.join('0x'+data[i:i+2] for i in range(0,len(data),2))+'}'
    envmask=lambda item:sum(1<<ENV[e] for e in item['environments'])
    private=['/* Generated reviewed catalog; no runtime/game payloads. */','static const NpCompatProfile s_profiles[] = {']
    for p in profiles:
        private.append('    {NP_RUNTIME_KNOWN,%uu,%uu,%s,%s,%s,%s,%s},'%(envmask(p),sum(fixes[n][0] for n in p['fixes']),string(p['serial']),bytearray_c(p['disc_sha256']),string(p['id']),string(p['game']),string(p['revision'])))
    if not profiles:private.append('    {0},')
    private+=['};','#define NP_CATALOG_PROFILES %uu'%len(profiles),'static const NpCatalogPatch s_catalogPatches[] = {']
    count=0
    for p in patches:
        for w in p['writes']:
            private.append('    {%uu,%uu,0x%08xu,%uu,%s,%s},'%(p['bit'],envmask(p),int(w['address'],0),len(bytes.fromhex(w['expected'])),bytearray_c(w['expected']),bytearray_c(w['replacement'])))
            count+=1
    if not count:private.append('    {0},')
    require(count<=256,'Catalog write limit exceeded')
    private+=['};','#define NP_CATALOG_PATCHES %uu'%count,'']
    return {'include/psxcore_profile_catalog.h':'\n'.join(public),'src/compat_profiles.generated.h':'\n'.join(private)}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[2]);parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    try:
        outputs=render(args.root/'compatibility')
        for name,text in outputs.items():
            path=args.root/name
            if args.check:require(path.is_file() and path.read_text()==text,'Generated catalog stale: '+name)
            else:path.write_text(text,encoding='utf-8')
    except (ValueError,KeyError,TypeError) as error:parser.error(str(error))
    print('Compatibility catalog verified' if args.check else 'Compatibility catalog generated')

if __name__=='__main__':main()
